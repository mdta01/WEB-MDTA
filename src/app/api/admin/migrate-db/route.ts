import { NextRequest, NextResponse } from 'next/server'
import { exec } from 'child_process'
import { promisify } from 'util'
import path from 'path'
import { isAdminAuthenticated } from '@/lib/auth'

export const runtime = 'nodejs'
export const dynamic = 'force-dynamic'
export const maxDuration = 60 // 60s — Vercel hobby plan max

const execAsync = promisify(exec)

/**
 * POST /api/admin/migrate-db
 *
 * Triggers `prisma db push --accept-data-loss` on the server (Vercel function).
 * Creates any missing tables/columns in the production Neon database based on
 * the current schema.prisma — used to create the Visitor & PageView tables
 * after the visitor tracking feature was added.
 *
 * Auth: requires admin session cookie.
 *
 * Implementation notes:
 * — Uses `node_modules/.bin/prisma` directly (not `npx`) for reliability &
 *   speed in Vercel serverless (avoids registry lookup).
 * — 55s timeout — leaves 5s buffer before function's 60s limit.
 * — `--accept-data-loss`: skip interactive confirmation (CI-safe).
 * — `--skip-generate`: Prisma Client already generated by postinstall hook.
 *
 * Returns:
 * — 200 with stdout/stderr on success
 * — 500 with error message + hint on failure
 */
export async function POST(_request: NextRequest) {
  const authed = await isAdminAuthenticated()
  if (!authed) {
    return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })
  }

  try {
    // Use direct binary path — more reliable than `npx` in serverless env
    const prismaBin = path.join(process.cwd(), 'node_modules', '.bin', 'prisma')
    const schemaPath = path.join(process.cwd(), 'prisma', 'schema.prisma')

    const { stdout, stderr } = await execAsync(
      `"${prismaBin}" db push --accept-data-loss --skip-generate --schema="${schemaPath}"`,
      {
        cwd: process.cwd(),
        timeout: 55000, // 55s — leave 5s buffer before function timeout
        maxBuffer: 1024 * 1024, // 1MB output buffer
        env: {
          ...process.env,
          // Ensure prisma uses the correct schema file
          PRISMA_SCHEMA_PATH: schemaPath,
        },
      }
    )

    // Prisma often writes progress to stderr (not an error, just info)
    const output = (stdout + (stderr ? '\n--- stderr ---\n' + stderr : '')).trim()

    // Detect success keywords in output
    const success = output.includes('🚀  Your database is now in sync') ||
                    output.includes('Your database is now in sync') ||
                    output.toLowerCase().includes('applied') ||
                    output === ''

    return NextResponse.json({
      success: true,
      message: 'Schema berhasil di-push ke database. Tabel Visitor & PageView (dan tabel lain yang hilang) sudah dibuat.',
      output: output.substring(0, 4000), // truncate for response size
      schemaSynced: success,
      ts: new Date().toISOString(),
    })
  } catch (error) {
    console.error('[migrate-db] Error:', error)

    // Extract useful error message from child_process error
    const err = error as { stdout?: string; stderr?: string; message?: string; killed?: boolean; code?: number }
    const errorOutput = (err.stdout || '') + (err.stderr ? '\n' + err.stderr : '')

    // Check common failure causes & provide actionable hints
    let hint = ''
    if (errorOutput.includes('DIRECT_URL') || errorOutput.includes('directUrl')) {
      hint = 'Environment variable DIRECT_URL belum di-set di Vercel. Set di: Vercel Dashboard → Project → Settings → Environment Variables. Format: postgresql://user:pass@host/db?sslmode=require (gunakan direct connection, bukan pooler)'
    } else if (errorOutput.includes('DATABASE_URL')) {
      hint = 'Environment variable DATABASE_URL belum di-set di Vercel. Set di: Vercel Dashboard → Project → Settings → Environment Variables.'
    } else if (errorOutput.includes('ECONNREFUSED') || errorOutput.includes('ECONNRESET')) {
      hint = ' Tidak bisa connect ke database. Cek koneksi Neon, pastikan DB aktif (Neon free tier bisa sleep).'
    } else if (errorOutput.includes('P1003') || errorOutput.includes('does not exist')) {
      hint = ' Database belum ada. Buat database di Neon dashboard dulu, lalu set DATABASE_URL & DIRECT_URL di Vercel.'
    } else if (err.killed || err.code === 124) {
      hint = ' Proses timeout (>55s). Database mungkin terlalu besar atau koneksi lambat. Coba jalankan manual: bun run db:push setelah vercel env pull.'
    } else if (err.code === 127 || errorOutput.includes('command not found')) {
      hint = ' Prisma binary tidak ditemukan. Pastikan `prisma` ada di dependencies (bukan devDependencies).'
    }

    return NextResponse.json({
      success: false,
      error: 'Gagal menjalankan prisma db push',
      output: (errorOutput || err.message || 'Unknown error').substring(0, 4000),
      hint: hint.trim(),
      exitCode: err.code,
      ts: new Date().toISOString(),
    }, { status: 500 })
  }
}

